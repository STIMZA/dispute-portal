create table notifications (
    id         bigint generated by default as identity primary key,
    recipient  varchar(50)  not null,
    dispute_id bigint       not null,
    message    varchar(300) not null,
    created_at timestamp    not null,
    read_at    timestamp,
    constraint fk_notifications_dispute foreign key (dispute_id) references disputes (id)
);

create index ix_notifications_recipient_created on notifications (recipient, created_at);
create index ix_notifications_recipient_read on notifications (recipient, read_at);

create table dispute_evidence (
    id                bigint generated by default as identity primary key,
    dispute_id        bigint       not null,
    original_filename varchar(150) not null,
    content_type      varchar(50)  not null,
    size_bytes        bigint       not null,
    storage_key       varchar(32)  not null,
    sha256            varchar(64)  not null,
    uploaded_by       varchar(50)  not null,
    uploaded_at       timestamp    not null,
    constraint fk_dispute_evidence_dispute foreign key (dispute_id) references disputes (id),
    constraint uk_dispute_evidence_key unique (storage_key),
    constraint uk_dispute_evidence_hash unique (dispute_id, sha256)
);

create index ix_dispute_evidence_dispute on dispute_evidence (dispute_id, uploaded_at);
