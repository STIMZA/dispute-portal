create table customers (
    id            bigint generated by default as identity primary key,
    username      varchar(50)  not null,
    password_hash varchar(100) not null,
    full_name     varchar(100) not null,
    constraint uk_customers_username unique (username)
);

create table transactions (
    id               bigint generated by default as identity primary key,
    customer_id      bigint        not null,
    reference        varchar(30)   not null,
    merchant         varchar(100)  not null,
    description      varchar(255),
    amount           decimal(12,2) not null,
    currency         varchar(3)    not null,
    transaction_date timestamp     not null,
    constraint uk_transactions_reference unique (reference),
    constraint fk_transactions_customer foreign key (customer_id) references customers (id)
);

create index ix_transactions_customer_date on transactions (customer_id, transaction_date);

create table disputes (
    id              bigint generated by default as identity primary key,
    transaction_id  bigint        not null,
    reason          varchar(40)   not null,
    details         varchar(1000) not null,
    status          varchar(30)   not null,
    resolution_note varchar(500),
    created_at      timestamp     not null,
    created_by      varchar(50)   not null,
    updated_at      timestamp     not null,
    constraint fk_disputes_transaction foreign key (transaction_id) references transactions (id)
);

create index ix_disputes_transaction on disputes (transaction_id);
create index ix_disputes_status on disputes (status);
