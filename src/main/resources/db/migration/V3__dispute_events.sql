-- Append-only history of everything that happens to a dispute.
create table dispute_events (
    id          bigint generated by default as identity primary key,
    dispute_id  bigint      not null,
    from_status varchar(30),
    to_status   varchar(30) not null,
    note        varchar(500),
    actor       varchar(50) not null,
    created_at  timestamp   not null,
    constraint fk_dispute_events_dispute foreign key (dispute_id) references disputes (id)
);

create index ix_dispute_events_dispute on dispute_events (dispute_id, created_at);

-- Backfill: every existing dispute was raised, and any that moved on had one change.
insert into dispute_events (dispute_id, from_status, to_status, note, actor, created_at)
select id, null, 'SUBMITTED', null, created_by, created_at from disputes;

insert into dispute_events (dispute_id, from_status, to_status, note, actor, created_at)
select id, 'SUBMITTED', status, resolution_note, coalesce(updated_by, created_by), updated_at
from disputes where status <> 'SUBMITTED';
