package com.example.disputeportal.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/** A customer's dispute against a transaction. Kept permanently to provide the dispute history. */
@Entity
@Table(name = "disputes")
public class Dispute {

    /**
     * Primary key, generated by the database (an identity column).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The transaction being disputed. A transaction can have several disputes over time, but only one open at a time.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "transaction_id")
    private BankTransaction transaction;

    /**
     * Why the customer is disputing, chosen from a fixed list.
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 40)
    private DisputeReason reason;

    /**
     * The customer's own description of what happened.
     */
    @Column(nullable = false, length = 1000)
    private String details;

    /**
     * Where the dispute is in its workflow (see {@link DisputeStatus}).
     */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private DisputeStatus status;

    /**
     * The admin's latest note to the customer. Required when a dispute is resolved or rejected.
     */
    @Column(name = "resolution_note", length = 500)
    private String resolutionNote;

    /**
     * When it was raised (UTC). Never changes.
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Username of the customer who raised it.
     */
    @Column(name = "created_by", nullable = false, updatable = false, length = 50)
    private String createdBy;

    /**
     * When it last changed (UTC).
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Username of whoever changed it last: the customer when raised, then an admin. Full history is in {@link DisputeEvent}.
     */
    @Column(name = "updated_by", length = 50)
    private String updatedBy;

    protected Dispute() {
        // required by JPA
    }

    /**
     * Creates a new dispute. It always starts as SUBMITTED.
     */
    public Dispute(BankTransaction transaction, DisputeReason reason, String details,
                   String createdBy, LocalDateTime createdAt) {
        this.transaction = transaction;
        this.reason = reason;
        this.details = details;
        this.createdBy = createdBy;
        this.createdAt = createdAt;
        this.updatedAt = createdAt;
        this.updatedBy = createdBy;
        this.status = DisputeStatus.SUBMITTED;
    }

    /** Used by back-office processing (and the demo seeder) to move a dispute along. */
    public void changeStatus(DisputeStatus newStatus, String note, LocalDateTime at, String by) {
        this.status = newStatus;
        this.resolutionNote = note;
        this.updatedAt = at;
        this.updatedBy = by;
    }

    public Long getId() {
        return id;
    }

    public BankTransaction getTransaction() {
        return transaction;
    }

    public DisputeReason getReason() {
        return reason;
    }

    public String getDetails() {
        return details;
    }

    public DisputeStatus getStatus() {
        return status;
    }

    public String getResolutionNote() {
        return resolutionNote;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }

    public String getUpdatedBy() {
        return updatedBy;
    }
}
