package com.example.disputeportal.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/** One entry in a dispute's history. Rows are only ever inserted, never updated or deleted. */
@Entity
@Table(name = "dispute_events")
public class DisputeEvent {

    /**
     * Primary key, generated by the database (an identity column).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The dispute this entry belongs to.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "dispute_id", updatable = false)
    private Dispute dispute;

    /**
     * Status before the change. Null for the first entry, which records the dispute being raised.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "from_status", length = 30, updatable = false)
    private DisputeStatus fromStatus;

    /**
     * Status after the change.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "to_status", nullable = false, length = 30, updatable = false)
    private DisputeStatus toStatus;

    /**
     * The admin's note at that moment, if any.
     */
    @Column(length = 500, updatable = false)
    private String note;

    /**
     * Username of whoever caused the change: the customer or an admin.
     */
    @Column(nullable = false, length = 50, updatable = false)
    private String actor;

    /**
     * When it happened (UTC).
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    protected DisputeEvent() {
        // required by JPA
    }

    /** @param fromStatus null for the event that records the dispute being raised */
    public DisputeEvent(Dispute dispute, DisputeStatus fromStatus, DisputeStatus toStatus, String note,
                        String actor, LocalDateTime createdAt) {
        this.dispute = dispute;
        this.fromStatus = fromStatus;
        this.toStatus = toStatus;
        this.note = note;
        this.actor = actor;
        this.createdAt = createdAt;
    }

    public Long getId() {
        return id;
    }

    public Dispute getDispute() {
        return dispute;
    }

    public DisputeStatus getFromStatus() {
        return fromStatus;
    }

    public DisputeStatus getToStatus() {
        return toStatus;
    }

    public String getNote() {
        return note;
    }

    public String getActor() {
        return actor;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }
}
