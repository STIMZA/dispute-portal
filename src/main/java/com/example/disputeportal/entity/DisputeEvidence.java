package com.example.disputeportal.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/**
 * The record of one uploaded file. Only the metadata lives in the database; the bytes are kept by the evidence
 * storage under {@link #getStorageKey()}. Rows are never updated: evidence stays attached to the dispute for good.
 */
@Entity
@Table(name = "dispute_evidence")
public class DisputeEvidence {

    /**
     * Primary key, generated by the database (an identity column).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The dispute the file supports.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "dispute_id", updatable = false)
    private Dispute dispute;

    /**
     * The file name shown to people, already cleaned of path parts and control characters. It is never used to
     * build a path on disk.
     */
    @Column(name = "original_filename", nullable = false, updatable = false, length = 150)
    private String originalFilename;

    /**
     * The real type, worked out from the file's first bytes (not the browser's claim). Used as the download type.
     */
    @Column(name = "content_type", nullable = false, updatable = false, length = 50)
    private String contentType;

    /**
     * Size in bytes.
     */
    @Column(name = "size_bytes", nullable = false, updatable = false)
    private long sizeBytes;

    /**
     * Random name of the stored file (32 hex characters). Unrelated to anything the user typed.
     */
    @Column(name = "storage_key", nullable = false, updatable = false, length = 32)
    private String storageKey;

    /**
     * SHA-256 of the content (hex). Used to refuse the same file twice on one dispute, and as an integrity record.
     */
    @Column(nullable = false, updatable = false, length = 64)
    private String sha256;

    /**
     * Username of whoever uploaded it.
     */
    @Column(name = "uploaded_by", nullable = false, updatable = false, length = 50)
    private String uploadedBy;

    /**
     * When it was uploaded (UTC).
     */
    @Column(name = "uploaded_at", nullable = false, updatable = false)
    private LocalDateTime uploadedAt;

    protected DisputeEvidence() {
        // required by JPA
    }

    public DisputeEvidence(Dispute dispute, String originalFilename, String contentType, long sizeBytes,
                           String storageKey, String sha256, String uploadedBy, LocalDateTime uploadedAt) {
        this.dispute = dispute;
        this.originalFilename = originalFilename;
        this.contentType = contentType;
        this.sizeBytes = sizeBytes;
        this.storageKey = storageKey;
        this.sha256 = sha256;
        this.uploadedBy = uploadedBy;
        this.uploadedAt = uploadedAt;
    }

    public Long getId() {
        return id;
    }

    public Dispute getDispute() {
        return dispute;
    }

    public String getOriginalFilename() {
        return originalFilename;
    }

    public String getContentType() {
        return contentType;
    }

    public long getSizeBytes() {
        return sizeBytes;
    }

    public String getStorageKey() {
        return storageKey;
    }

    public String getSha256() {
        return sha256;
    }

    public String getUploadedBy() {
        return uploadedBy;
    }

    public LocalDateTime getUploadedAt() {
        return uploadedAt;
    }
}
