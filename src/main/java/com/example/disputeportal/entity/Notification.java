package com.example.disputeportal.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/**
 * An in-app message for one user about a dispute (a customer is told about decisions, admins about new disputes and
 * new evidence). The text is a snapshot written when the event happened, so later edits never rewrite what was sent.
 */
@Entity
@Table(name = "notifications")
public class Notification {

    /**
     * Primary key, generated by the database (an identity column).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Username of the person who should see this. Every read is scoped to it, so nobody can open another user's.
     */
    @Column(nullable = false, updatable = false, length = 50)
    private String recipient;

    /**
     * The dispute this is about. Kept as a plain id: the list page only needs it to build a link.
     */
    @Column(name = "dispute_id", nullable = false, updatable = false)
    private Long disputeId;

    /**
     * What happened, in a sentence.
     */
    @Column(nullable = false, updatable = false, length = 300)
    private String message;

    /**
     * When it was created (UTC).
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * When the recipient marked it as read (UTC). Null while it is still unread.
     */
    @Column(name = "read_at")
    private LocalDateTime readAt;

    protected Notification() {
        // required by JPA
    }

    public Notification(String recipient, Long disputeId, String message, LocalDateTime createdAt) {
        this.recipient = recipient;
        this.disputeId = disputeId;
        this.message = message;
        this.createdAt = createdAt;
    }

    /** Marks it as read. Does nothing if it already was, so the first read time is kept. */
    public void markRead(LocalDateTime at) {
        if (readAt == null) {
            readAt = at;
        }
    }

    public boolean isRead() {
        return readAt != null;
    }

    public Long getId() {
        return id;
    }

    public String getRecipient() {
        return recipient;
    }

    public Long getDisputeId() {
        return disputeId;
    }

    public String getMessage() {
        return message;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getReadAt() {
        return readAt;
    }
}
