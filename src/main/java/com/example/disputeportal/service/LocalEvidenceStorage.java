package com.example.disputeportal.service;

import com.example.disputeportal.config.EvidenceProperties;
import com.example.disputeportal.exception.ResourceNotFoundException;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.regex.Pattern;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Component;

/**
 * Keeps evidence in one folder on disk. File names are the random keys generated by {@link EvidenceService}, and a key
 * is checked against a strict pattern before it is turned into a path, so nothing a user types can reach outside the
 * folder.
 */
@Component
public class LocalEvidenceStorage implements EvidenceStorage {

    private static final Logger log = LoggerFactory.getLogger(LocalEvidenceStorage.class);

    /** Keys are 32 lowercase hex characters (a UUID without dashes). */
    private static final Pattern KEY = Pattern.compile("[0-9a-f]{32}");

    private final Path root;

    /** Creates the folder if needed. Failing here stops the app at startup, which is better than failing on upload. */
    public LocalEvidenceStorage(EvidenceProperties properties) {
        this.root = Path.of(properties.storageDir()).toAbsolutePath().normalize();
        try {
            Files.createDirectories(root);
        } catch (IOException ex) {
            throw new UncheckedIOException("Cannot create the evidence folder " + root, ex);
        }
        log.info("Evidence is stored in {}", root);
    }

    @Override
    public void store(String key, byte[] content) {
        try {
            // CREATE_NEW refuses to overwrite: a key is only ever written once.
            Files.write(resolve(key), content, StandardOpenOption.CREATE_NEW, StandardOpenOption.WRITE);
        } catch (IOException ex) {
            throw new UncheckedIOException("Could not store evidence file", ex);
        }
    }

    @Override
    public Resource load(String key) {
        Path file = resolve(key);
        if (!Files.isRegularFile(file)) {
            log.error("Evidence file {} is recorded in the database but missing from {}", key, root);
            throw new ResourceNotFoundException("Evidence file not found");
        }
        return new FileSystemResource(file);
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException | RuntimeException ex) {
            log.warn("Could not delete evidence file {}", key, ex);
        }
    }

    private Path resolve(String key) {
        if (key == null || !KEY.matcher(key).matches()) {
            throw new IllegalArgumentException("Invalid storage key");
        }
        return root.resolve(key);
    }
}
